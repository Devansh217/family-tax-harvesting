// The `alerts` server function (Deno), called daily by Supabase Cron. All logic is in ../_shared/alerts.ts, tested with
// Vitest; this file wires the clients, secrets and the engine bundle. The bundle is generated: run `npm run build:engine`
// before deploying (it writes ../_shared/engine.js). Deploy: npx supabase@2 functions deploy alerts --no-verify-jwt
import { createClient } from 'npm:@supabase/supabase-js@2.118.0';
import { parseFunds, parsePrices, runAlerts, rehearsalDate, sampleEmail, secretMatches, type AlertsDb, type LogKind } from '../_shared/alerts.ts';
import { sendEmail } from '../_shared/email.ts';
import { importKeyRing } from '../_shared/envelope.ts';
// @ts-ignore generated by `npm run build:engine`
import * as engine from '../_shared/engine.js';

const service = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!, { auth: { persistSession: false } });

const db: AlertsDb = {
  async optedIn() {
    const { data, error } = await service.from('season_alert_families').select('user_id, email, version, envelope, updated_at');
    if (error) throw error;
    return (data ?? []).map((r) => ({ userId: r.user_id, email: r.email ?? '', version: r.version, envelope: r.envelope, updatedAt: r.updated_at }));
  },
  async logged(userId, kind: LogKind, onDate) {
    const { data, error } = await service.from('season_log').select('id, sent').eq('family_user_id', userId).eq('kind', kind).eq('on_date', onDate).maybeSingle();
    if (error) throw error;
    return { exists: !!data, sent: data?.sent === true };
  },
  async log(userId, kind: LogKind, onDate) {
    const { error } = await service.from('season_log').insert({ family_user_id: userId, kind, on_date: onDate });
    if (error?.code === '23505') return false;
    if (error) throw error;
    return true;
  },
  async markSent(userId, kind: LogKind, onDate) {
    const { error } = await service.from('season_log').update({ sent: true }).eq('family_user_id', userId).eq('kind', kind).eq('on_date', onDate);
    if (error) throw error;
  },
  async unlog(userId, kind: LogKind, onDate) {
    const { error } = await service.from('season_log').delete().eq('family_user_id', userId).eq('kind', kind).eq('on_date', onDate);
    if (error) throw error;
  },
  async saveStats(row) {
    const { error } = await service.from('season_stats').upsert(row, { onConflict: 'week' });
    if (error) throw error;
  },
};

Deno.serve(async (req) => {
  if (!secretMatches(req.headers.get('x-alerts-secret'), Deno.env.get('ALERTS_SECRET'))) return new Response('forbidden', { status: 403 });
  try {
    const appUrl = Deno.env.get('APP_URL')!;
    const apiKey = Deno.env.get('BREVO_API_KEY')!, sender = Deno.env.get('ALERTS_SENDER')!;
    // Pre-season check of the email provider: a fixed sample, no family data, to the sender's own address.
    if (req.headers.get('x-alerts-test') === '1') {
      const m = sampleEmail(appUrl);
      await sendEmail(sender, m.subject, m.text, { apiKey, sender, fetch });
      return new Response(JSON.stringify({ test: 'sent' }), { status: 200, headers: { 'Content-Type': 'application/json' } });
    }
    // Wrong prices or fund types would mean wrong numbers in an email, so a failed or malformed fetch skips the whole run.
    const base = appUrl.endsWith('/') ? appUrl : `${appUrl}/`;
    const get = async (file: string) => {
      const res = await fetch(new URL(`prices/${file}`, base));
      return res.ok ? await res.json().catch(() => null) : null;
    };
    const prices = parsePrices(await get('latest.json')), funds = parseFunds(await get('funds.json'));
    if (!prices || !funds) { console.error('alerts: market files missing or malformed; run skipped'); return new Response(JSON.stringify({ skipped: 'market' }), { status: 200 }); }
    // Rehearsal: with the secret, `x-alerts-date` runs as if it were that date (1 Feb to 31 Mar). It logs and sends as normal but writes no season totals.
    const dateHeader = req.headers.get('x-alerts-date');
    const rehearsal = dateHeader !== null ? rehearsalDate(dateHeader, engine.FY_2026_27.end) : null;
    if (dateHeader !== null && !rehearsal) return new Response('bad date', { status: 400 });
    const today = rehearsal ?? engine.todayISO(); // India date, computed once
    const out = await runAlerts(today, {
      db, ring: await importKeyRing(Deno.env.get('FAMILY_KEYS')!, Deno.env.get('FAMILY_KEY_CURRENT')!), prices, funds, appUrl,
      engine: {
        withFunds: engine.withFunds, withPrices: engine.withPrices, computeFamily: engine.computeFamily, seasonSummary: engine.seasonSummary,
        lastSafeDay: engine.lastSafeDay, todayISO: engine.todayISO, rules: engine.FY_2026_27, holidays: engine.NSE_HOLIDAYS_2027,
      },
      send: (to, subject, text) => sendEmail(to, subject, text, { apiKey, sender, fetch }),
    }, { rehearsal: !!rehearsal });
    console.log('alerts', JSON.stringify(out)); // counts only
    return new Response(JSON.stringify(out), { status: 200, headers: { 'Content-Type': 'application/json' } });
  } catch (e) {
    const err = e as { code?: string; name?: string } | null;
    console.error('alerts failed', err?.code ?? err?.name);
    return new Response('error', { status: 500 });
  }
});
